-- Backend state for admin dashboard notifications.
-- The notification list itself is still derived from backend data
-- (reports, community actions, evidence, pending registrations).
-- This table stores only read/dismiss state per admin.

create table if not exists public.admin_notification_states (
    state_id bigint generated by default as identity primary key,
    admin_user_id uuid not null references public.profiles(user_id) on delete cascade,
    notif_key text not null,
    read_at timestamptz,
    removed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (admin_user_id, notif_key)
);

create index if not exists admin_notification_states_admin_idx
    on public.admin_notification_states (admin_user_id);

alter table public.admin_notification_states enable row level security;

revoke all on public.admin_notification_states from public, anon;
grant select, insert, update on public.admin_notification_states to authenticated;

drop policy if exists admin_notification_state_select_own on public.admin_notification_states;
create policy admin_notification_state_select_own
    on public.admin_notification_states
    for select to authenticated
    using (admin_user_id = auth.uid());

drop policy if exists admin_notification_state_insert_own on public.admin_notification_states;
create policy admin_notification_state_insert_own
    on public.admin_notification_states
    for insert to authenticated
    with check (admin_user_id = auth.uid());

drop policy if exists admin_notification_state_update_own on public.admin_notification_states;
create policy admin_notification_state_update_own
    on public.admin_notification_states
    for update to authenticated
    using (admin_user_id = auth.uid())
    with check (admin_user_id = auth.uid());

-- Backend source for registration approval notifications.
create or replace function public.get_admin_pending_registrations()
returns table (
    registration_id uuid,
    full_name text,
    account_category text,
    created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
    select
        p.user_id,
        p.full_name,
        p.account_category,
        p.created_at
    from public.profiles p
    where p.account_status = 'pending'
      and p.region_id = (
          select region_id
          from public.profiles
          where user_id = auth.uid()
      )
      and exists (
          select 1
          from public.profiles ap
          join public.pkk_members m on m.user_id = ap.user_id
          join public.pkk_units u on u.pkk_unit_id = m.pkk_unit_id
          where ap.user_id = auth.uid()
            and ap.account_category = 'anggota_pkk'
            and ap.account_status = 'active'
            and m.member_role = 'leader'
            and m.status = 'verified'
            and u.region_id = p.region_id
            and u.verification_status = 'verified'
      )
    order by p.created_at desc;
$$;

revoke all on function public.get_admin_pending_registrations() from public, anon;
grant execute on function public.get_admin_pending_registrations() to authenticated;