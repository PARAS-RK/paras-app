-- Pembantu otorisasi Ketua PKK terverifikasi pada sebuah wilayah.
create or replace function public.paras_is_region_pkk_leader(p_region_id bigint)
returns boolean
language sql
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles p
        join public.pkk_members m on m.user_id = p.user_id
        join public.pkk_units u on u.pkk_unit_id = m.pkk_unit_id
        where p.user_id = auth.uid()
          and u.region_id = p_region_id
          and p.account_category = 'anggota_pkk'
          and p.account_status = 'active'
          and m.member_role = 'leader'
          and m.status = 'verified'
          and u.verification_status = 'verified'
    );
$$;

revoke all on function public.paras_is_region_pkk_leader(bigint) from public, anon;
grant execute on function public.paras_is_region_pkk_leader(bigint) to authenticated;

-- Draf bersifat privat: tidak dibaca zona publik.
create table if not exists public.community_action_drafts (
    draft_id bigint generated by default as identity primary key,
    cluster_key text not null,
    region_id bigint not null,
    source_report_ids bigint[] not null default '{}',
    title text not null,
    description text,
    steps text,
    participant_target integer,
    duration text,
    registration_range text,
    implementation_range text,
    location text,
    category text,
    updated_by uuid,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (region_id, cluster_key)
);

alter table public.community_action_drafts enable row level security;

drop policy if exists draft_select_leader on public.community_action_drafts;
create policy draft_select_leader on public.community_action_drafts
    for select to authenticated
    using (public.paras_is_region_pkk_leader(region_id));

drop policy if exists draft_insert_leader on public.community_action_drafts;
create policy draft_insert_leader on public.community_action_drafts
    for insert to authenticated
    with check (public.paras_is_region_pkk_leader(region_id));

drop policy if exists draft_update_leader on public.community_action_drafts;
create policy draft_update_leader on public.community_action_drafts
    for update to authenticated
    using (public.paras_is_region_pkk_leader(region_id))
    with check (public.paras_is_region_pkk_leader(region_id));

