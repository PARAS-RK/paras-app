-- Simpan draf yang sudah diedit Ketua PKK.
create or replace function public.save_community_action_draft(
    p_cluster_key text,
    p_region_id bigint,
    p_report_ids bigint[],
    p_draft jsonb
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not public.paras_is_region_pkk_leader(p_region_id) then
        raise exception 'Akses ditolak: hanya Ketua PKK wilayah ini yang dapat menyimpan draf.';
    end if;

    if p_cluster_key is null or btrim(p_cluster_key) = '' then
        raise exception 'Kunci klaster wajib diisi.';
    end if;

    if coalesce(array_length(p_report_ids, 1), 0) = 0 then
        raise exception 'Draf harus memiliki minimal satu laporan pembentuk.';
    end if;

    if exists (
        select 1
        from unnest(p_report_ids) as rid
        where not exists (
            select 1 from public.reports r
            where r.report_id = rid and r.region_id = p_region_id
        )
    ) then
        raise exception 'Ada laporan pembentuk yang tidak berada pada wilayah ini.';
    end if;

    insert into public.community_action_drafts (
        cluster_key,
        region_id,
        source_report_ids,
        title,
        description,
        steps,
        participant_target,
        duration,
        registration_range,
        implementation_range,
        location,
        category,
        updated_by,
        created_at,
        updated_at
    )
    values (
        btrim(p_cluster_key),
        p_region_id,
        p_report_ids,
        coalesce(nullif(p_draft->>'name', ''), 'Aksi komunitas'),
        nullif(p_draft->>'description', ''),
        nullif(p_draft->>'steps', ''),
        nullif(p_draft->>'participantTarget', '')::integer,
        nullif(p_draft->>'duration', ''),
        nullif(p_draft->>'registrationRange', ''),
        nullif(p_draft->>'implementationRange', ''),
        nullif(p_draft->>'location', ''),
        nullif(p_draft->>'category', ''),
        auth.uid(),
        now(),
        now()
    )
    on conflict (region_id, cluster_key) do update
       set source_report_ids = excluded.source_report_ids,
           title = excluded.title,
           description = excluded.description,
           steps = excluded.steps,
           participant_target = excluded.participant_target,
           duration = excluded.duration,
           registration_range = excluded.registration_range,
           implementation_range = excluded.implementation_range,
           location = excluded.location,
           category = excluded.category,
           updated_by = excluded.updated_by,
           updated_at = now();
end;
$$;

revoke all on function public.save_community_action_draft(text, bigint, bigint[], jsonb) from public, anon;
grant execute on function public.save_community_action_draft(text, bigint, bigint[], jsonb) to authenticated;

-- Publish: buat aksi nyata yang langsung dibaca zona publik.
create or replace function public.publish_community_action(
    p_cluster_key text,
    p_region_id bigint,
    p_report_ids bigint[],
    p_draft jsonb
) returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_action_id bigint;
    v_title text;
    v_coordinator text;
    v_start_date date;
    v_date_text text;
    v_steps text;
begin
    if not public.paras_is_region_pkk_leader(p_region_id) then
        raise exception 'Akses ditolak: hanya Ketua PKK wilayah ini yang dapat menerbitkan aksi.';
    end if;

    if coalesce(array_length(p_report_ids, 1), 0) = 0 then
        raise exception 'Aksi harus memiliki minimal satu laporan pembentuk.';
    end if;

    if exists (
        select 1
        from unnest(p_report_ids) as rid
        where not exists (
            select 1 from public.reports r
            where r.report_id = rid and r.region_id = p_region_id
        )
    ) then
        raise exception 'Ada laporan pembentuk yang tidak berada pada wilayah ini.';
    end if;

    v_title := coalesce(nullif(btrim(p_draft->>'name'), ''), 'Aksi komunitas');
    v_steps := coalesce(p_draft->>'steps', '');

    select coalesce(nullif(btrim(full_name), ''), 'Ketua PKK')
      into v_coordinator
      from public.profiles
     where user_id = auth.uid();

    -- Kolom action_start_date bertipe date. Ambil tanggal pertama dari teks jadwal.
    v_date_text := regexp_replace(coalesce(p_draft->>'implementationRange', ''), '^\D*', '');
    v_date_text := split_part(split_part(v_date_text, '–', 1), '-', 1);
    begin
        v_start_date := to_date(btrim(v_date_text), 'DD Month YYYY');
    exception when others then
        v_start_date := current_date;
    end;

    insert into public.community_actions (
        action_title,
        action_description,
        region_id,
        action_start_date,
        action_due_date,
        action_coordinator,
        source_report_ids,
        participant_target,
        location,
        duration,
        registration_range,
        category,
        action_target,
        pkk_unit_id,
        created_at
    )
    values (
        v_title,
        nullif(p_draft->>'description', ''),
        p_region_id,
        v_start_date,
        v_start_date,
        coalesce(v_coordinator, 'Ketua PKK'),
        p_report_ids,
        nullif(p_draft->>'participantTarget', '')::integer,
        nullif(p_draft->>'location', ''),
        nullif(p_draft->>'duration', ''),
        nullif(p_draft->>'registrationRange', ''),
        nullif(p_draft->>'category', ''),
        nullif(p_draft->>'participantTarget', ''),
        (
            select pkk_unit_id
            from public.pkk_units
            where region_id = p_region_id
              and verification_status = 'verified'
            order by pkk_unit_id
            limit 1
        ),
        now()
    )
    returning action_id into v_action_id;

    insert into public.action_tasks (action_id, step_order, step_content, points)
    select
        v_action_id,
        row_number() over (order by item.ord),
        btrim(item.step),
        10
    from unnest(string_to_array(v_steps, E'\n')) with ordinality as item(step, ord)
    where btrim(item.step) <> '';

    -- Log publik: warga dapat melihat bahwa laporannya masuk ke aksi komunitas.
    insert into public.report_status_logs (
        report_id,
        log_status,
        log_notes,
        is_public,
        created_by,
        created_at
    )
    select
        rid,
        'in_progress',
        'Laporan tergabung dalam aksi komunitas "' || v_title || '".',
        true,
        auth.uid(),
        now()
    from unnest(p_report_ids) as rid;

    delete from public.community_action_drafts
     where region_id = p_region_id
       and cluster_key = p_cluster_key;

    return v_action_id;
end;
$$;

revoke all on function public.publish_community_action(text, bigint, bigint[], jsonb) from public, anon;
grant execute on function public.publish_community_action(text, bigint, bigint[], jsonb) to authenticated;

-- Verifikasi bukti warga oleh Ketua PKK wilayah aksi.
create or replace function public.set_action_proof_status(
    p_proof_id bigint,
    p_status text,
    p_reason text default null
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_region_id bigint;
begin
    if p_status not in ('pending', 'verified', 'rejected') then
        raise exception 'Status verifikasi tidak dikenal.';
    end if;

    select ca.region_id
      into v_region_id
      from public.action_completion_proofs pr
      join public.action_participants ap on ap.participation_id = pr.participation_id
      join public.community_actions ca on ca.action_id = pr.action_id
     where pr.proof_id = p_proof_id;

    if not found or not public.paras_is_region_pkk_leader(v_region_id) then
        raise exception 'Akses ditolak: bukti tidak ditemukan atau bukan wilayah Anda.';
    end if;

    update public.action_completion_proofs
       set verification_status = p_status,
           verification_notes = nullif(btrim(p_reason), ''),
           updated_at = now()
     where proof_id = p_proof_id;
end;
$$;

revoke all on function public.set_action_proof_status(bigint, text, text) from public, anon;
grant execute on function public.set_action_proof_status(bigint, text, text) to authenticated;

-- Menandai aksi komunitas selesai.
create or replace function public.complete_community_action(p_action_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_region_id bigint;
begin
    select region_id into v_region_id
      from public.community_actions
     where action_id = p_action_id;

    if not found or not public.paras_is_region_pkk_leader(v_region_id) then
        raise exception 'Akses ditolak: aksi tidak ditemukan atau bukan wilayah Anda.';
    end if;

    update public.community_actions
       set completed_at = coalesce(completed_at, now())
     where action_id = p_action_id;
end;
$$;

revoke all on function public.complete_community_action(bigint) from public, anon;
grant execute on function public.complete_community_action(bigint) to authenticated;
